import { checks, finalizeChecks } from './catalogue';
import { freshnessRules } from './rules';

// The catalogue document, generated from the code so it cannot drift. `scripts/catalogue-md.mjs`
// writes docs/architecture/check-catalogue.md from this function, and a test fails when the
// committed file differs, so adding a check without regenerating the document breaks the build.

const escapeCell = (value: string): string => value.replace(/\|/g, '\\|').replace(/\s*\n\s*/g, ' ');
const displayCategory = (category: string): string => category.replace(/_/g, ' ');

export function renderCatalogueMarkdown(): string {
  const lines: string[] = [];
  const counts = { page: 0, site: 0, finalize: 0 };
  for (const check of checks) counts[check.evaluator]++;

  lines.push('# Check catalogue', '');
  lines.push(
    '> Generated from `packages/checks/src` by `node packages/checks/scripts/catalogue-md.mjs`. Do not edit this file by hand: change a check and run the script.',
    '',
  );
  lines.push(
    `The catalogue has ${checks.length} checks: ${counts.page} page checks, ${counts.site} site checks and ${counts.finalize} cross-page checks. Page and site checks run in \`@agentic-seo/checks\` over the crawler’s facts. Cross-page checks are evaluated at finalize, in SQL against the crawl tables; the definition below is the contract for that SQL.`,
    '',
  );
  lines.push('## Checks', '');
  lines.push('| Id | What it checks | Category | Severity | Scope | Evaluator | Fix | Rules |');
  lines.push('|---|---|---|---|---|---|---|---|');
  for (const check of checks) {
    lines.push(
      `| \`${check.id}\` | ${escapeCell(check.title)} | ${displayCategory(check.category)} | ${check.severity} | ${check.scope} | ${check.evaluator} | ${
        check.fix ? `\`${check.fix.change}\`` : '—'
      } | ${check.rules?.map((rule) => `\`${rule}\``).join(', ') ?? '—'} |`,
    );
  }
  lines.push('');

  lines.push('## Cross-page definitions', '');
  lines.push('A finalize check fails when its definition is true. Evidence is what the finding must name.', '');
  for (const check of finalizeChecks) {
    lines.push(`### \`${check.id}\` — ${check.title}`, '');
    if (check.requiresCompleteGraph)
      lines.push('Requires a complete link graph. Graph checks are suppressed when coverage is truncated.', '');
    lines.push(check.definition, '');
  }

  lines.push('## Freshness rules', '');
  lines.push(
    'Checks that depend on a Google or web-platform change reference these rules. A rule is re-checked at its source and its date updated.',
    '',
  );
  lines.push('| Rule | Statement | Source | Reviewed |');
  lines.push('|---|---|---|---|');
  for (const rule of freshnessRules)
    lines.push(`| \`${rule.id}\` | ${escapeCell(rule.statement)} | [source](${rule.source}) | ${rule.reviewedAt} |`);
  lines.push('');

  return lines.join('\n');
}
