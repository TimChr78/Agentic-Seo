import { z } from 'zod';
import type { ChangeTypeName, SourceEditor } from './change-types';
import { pilotSlug } from './pilot';
import { type Refusal, refuse } from './refusal';

// The source mapping (ADR-0007 review update): the explicit, ordered configuration a person writes
// for one site, saying which route comes from which file, and how. Detecting a framework's routing
// automatically is a later job; guessing wrong here would edit the wrong file, so an unmapped route
// is a refusal, not a best effort.
//
// The pilot is GitHub TimChr78/martechsignal: static HTML in the repository, but blog posts and tool
// pages are generated by tools/build_*.py at deploy time. Editing the generated index.html loses the
// edit at the next build, so the mapping points blog routes at their Markdown drafts and refuses the
// generated tool pages outright. That refusal is the feature.

const MAX_PATH = 1_024;

/** A field of a change, as the editor names it. */
export type ChangeField = 'title' | 'description';

/**
 * Which frontmatter keys carry a change field, best first. The pilot's build_blog.py uses
 * `seo_title or title` for `<title>` and `seo_description` for the meta description, and derives the
 * post's route from `slug` or the slugified `title` when no `slug` is declared. A title change
 * therefore writes `seo_title` only: editing `title` would change the post's H1 and, without an
 * explicit `slug`, its route. A mapping that overrides `title` is honoured, but the editor refuses
 * the edit when it would move the route.
 */
export type FieldMap = Partial<Record<ChangeField, readonly string[]>>;

export const DEFAULT_FIELDS: FieldMap = {
  title: ['seo_title'],
  description: ['seo_description'],
};

/**
 * How a `markdown_frontmatter` source quotes a written value. `yaml` writes standard double-quoted
 * scalars. `strip_quotes` writes for a build that only removes surrounding quotes (the pilot's
 * tools/build_blog.py:parse_frontmatter), so it must pick a quote the value does not contain and
 * refuses values that would change under that parser.
 */
export type FrontmatterDialect = 'yaml' | 'strip_quotes';

const GeneratedEntryInput = z.union([
  z.string().min(1).max(MAX_PATH),
  z.strictObject({
    path: z.string().min(1).max(MAX_PATH).describe('A glob of repository paths that the build writes, e.g. blog/*/index.html'),
    reason: z.string().min(1).max(500).describe('Why a person must not edit it, and where to edit instead'),
  }),
]);

export interface GeneratedEntry {
  path: string;
  reason: string;
}

export const SourceRuleSchema = z.strictObject({
  routes: z
    .string()
    .min(1)
    .max(MAX_PATH)
    .describe('A route pattern: an exact path (/about/), a parameter (/blog/:slug/) or a splat (/tools/*/)'),
  source: z
    .string()
    .min(1)
    .max(MAX_PATH)
    .describe(
      'A repository path template for that route, e.g. content/drafts/:slug-*.md (* matches a dated file name); with resolveBy frontmatter_slug, a glob of the files to read, e.g. content/drafts/*.md',
    ),
  editor: z.enum(['html', 'markdown_frontmatter']).describe('How the source is edited'),
  resolveBy: z
    .enum(['path', 'frontmatter_slug'])
    .default('path')
    .describe(
      "How the route finds its file: 'path' fills the source template from the route (a `*` in it is a file glob); 'frontmatter_slug' reads the `slug` (or slugified `title`) of every file matching the source glob, which is how a build names a post after its content rather than its file name",
    ),
  frontmatterDialect: z
    .enum(['yaml', 'strip_quotes'])
    .default('yaml')
    .describe(
      "markdown_frontmatter: how written values are quoted. 'yaml' is standard; 'strip_quotes' matches a build that only strips surrounding quotes (the pilot's build_blog.py)",
    ),
  fields: z
    .record(z.string(), z.array(z.string().min(1).max(120)).min(1))
    .optional()
    .describe(
      'markdown_frontmatter: change field -> frontmatter keys, best first. meta.title names the key the page title is read from (the pilot: seo_title), not the key the build derives the route from (the build refuses an edit that would move the route either way)',
    ),
  generated: z.boolean().default(false).describe('The route is served from a file the build writes; resolve it, but refuse to edit it'),
  generatedReason: z.string().min(1).max(500).optional().describe('Why the generated file must not be edited, and what to edit instead'),
  layout: z.boolean().default(false).describe('The source is a shared template; a change to it reaches every route the pattern matches'),
});

export const RedirectsConfigSchema = z.strictObject({
  file: z.string().min(1).max(MAX_PATH).default('_redirects').describe('The redirects file in the repository, e.g. _redirects'),
  format: z.literal('netlify').default('netlify').describe('Cloudflare Pages and Netlify share this format'),
});

export const SiteMappingSchema = z.strictObject({
  site: z.string().min(1).max(253).optional().describe('The host this mapping is for, e.g. martechsignal.com'),
  rules: z.array(SourceRuleSchema).min(1).max(200).describe('Ordered: the first rule whose route pattern matches wins'),
  redirects: RedirectsConfigSchema.optional(),
  generated: z
    .array(GeneratedEntryInput)
    .max(200)
    .default([])
    .describe('Repository paths the build writes; resolving to one is refused with the reason'),
});

export type SourceRule = z.infer<typeof SourceRuleSchema>;
export type SiteMappingInput = z.input<typeof SiteMappingSchema>;
export type SiteMapping = z.output<typeof SiteMappingSchema>;

/** Normalise the `generated` entries, which may be written as a plain path. */
export function generatedEntries(mapping: SiteMapping): GeneratedEntry[] {
  return mapping.generated.map((entry) =>
    typeof entry === 'string'
      ? {
          path: entry,
          reason: 'The site build writes this path, so an edit would be overwritten at the next build. Change its source instead.',
        }
      : entry,
  );
}

export function parseMapping(value: unknown): { ok: true; mapping: SiteMapping } | Refusal {
  const parsed = SiteMappingSchema.safeParse(value);
  if (!parsed.success) {
    const first = parsed.error.issues[0];
    return refuse(
      'invalid',
      first ? `The source mapping is not valid: ${first.path.join('.') || 'mapping'} ${first.message}` : 'The source mapping is not valid.',
    );
  }
  return { ok: true, mapping: parsed.data };
}

/** Which change types each source editor can write. The mapping adds nothing here. */
export const EDITOR_CAPABILITIES: Readonly<Record<SourceEditor, readonly ChangeTypeName[]>> = {
  html: ['meta.title', 'meta.description', 'schema.jsonld', 'image.alt'],
  markdown_frontmatter: ['meta.title', 'meta.description'],
};

// ---------------------------------------------------------------------------------------------
// Route and path patterns
// ---------------------------------------------------------------------------------------------

interface RoutePattern {
  pattern: string;
  regex: RegExp;
  params: string[];
  splat: boolean;
  exact: boolean;
}

/**
 * `:name` is one path segment and `*` is a splat. A parameter that shares its segment with literals
 * (`:slug-*.md`) is a source-template concern, not a route pattern, so it stays literal here and
 * therefore matches nothing: a mapping that confused the two is visible instead of over-broad.
 */
function compileRoute(pattern: string): RoutePattern {
  const params: string[] = [];
  let splat = false;
  let source = '^';
  let index = 0;
  while (index < pattern.length) {
    const char = pattern[index]!;
    if (char === '*') {
      splat = true;
      source += '(.*)';
      index += 1;
      continue;
    }
    if (char === ':') {
      const match = /^:([A-Za-z0-9_]+)/.exec(pattern.slice(index));
      if (match) {
        const rest = pattern.slice(index + match[0].length);
        if (rest === '' || rest.startsWith('/')) {
          params.push(match[1]!);
          source += '([^/]+)';
          index += match[0].length;
          continue;
        }
      }
    }
    source += char.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    index += 1;
  }
  source += '$';
  return { pattern, regex: new RegExp(source), params, splat, exact: params.length === 0 && !splat };
}

const compiledRoutes = new Map<string, RoutePattern>();
function routePattern(pattern: string): RoutePattern {
  const cached = compiledRoutes.get(pattern);
  if (cached) return cached;
  const compiled = compileRoute(pattern);
  compiledRoutes.set(pattern, compiled);
  return compiled;
}

function pathOf(route: string): string {
  try {
    return new URL(route).pathname;
  } catch {
    const withoutQuery = route.split('#')[0]!.split('?')[0]!;
    return withoutQuery.startsWith('/') ? withoutQuery : `/${withoutQuery}`;
  }
}

/** Decode a path value without throwing on a stray `%`. */
function safeDecode(value: string): string {
  try {
    return decodeURIComponent(value);
  } catch {
    return value;
  }
}

/** Match one route against a rule's pattern; the values are keyed by parameter name. */
export function matchRoute(pattern: string, route: string): Record<string, string> | null {
  const compiled = routePattern(pattern);
  const matched = compiled.regex.exec(pathOf(route));
  if (!matched) return null;
  const values: Record<string, string> = {};
  compiled.params.forEach((name, index) => {
    values[name] = safeDecode(matched[index + 1] ?? '');
  });
  if (compiled.splat) values['*'] = safeDecode(matched[compiled.params.length + 1] ?? '');
  return values;
}

/** Whether a route pattern matches a route (used for layout reach and generated paths). */
export function routeMatches(pattern: string, route: string): boolean {
  return matchRoute(pattern, route) !== null;
}

function globToRegex(glob: string): RegExp {
  let source = '^';
  for (const char of glob) {
    if (char === '*') source += '[^/]*';
    else if (char === '?') source += '[^/]';
    else source += char.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  }
  return new RegExp(`${source}$`);
}

/** Whether a repository path matches a mapping glob (`*` stays inside one path segment). */
export function pathMatchesGlob(glob: string, path: string): boolean {
  return globToRegex(glob).test(path);
}

/** The literal prefix of a glob, as much as can be listed: `content/drafts/` for `content/drafts/*.md`. */
export function globPrefix(glob: string): string {
  const star = glob.indexOf('*');
  if (star === -1) return glob;
  const before = glob.slice(0, star);
  const slash = before.lastIndexOf('/');
  return slash === -1 ? '' : before.slice(0, slash + 1);
}

// ---------------------------------------------------------------------------------------------
// Resolution
// ---------------------------------------------------------------------------------------------

/** Repository paths under a literal prefix (a directory, with a trailing slash); never the network. */
export type ListFiles = (prefix: string) => Promise<readonly string[]>;

export interface ResolveDeps {
  listFiles: ListFiles;
  /** The change type, so an editor that cannot express it is refused with a reason before editing. */
  changeType?: ChangeTypeName;
  /**
   * Reads a repository file's text. Required by a `resolveBy: 'frontmatter_slug'` rule, which has
   * to read each matching draft to learn the slug its build gives the post.
   */
  readFile?: (path: string) => Promise<string>;
  /**
   * Optional cache of file texts (keyed by repository path), so resolving several routes does not
   * re-read every draft. A caller that resolves a page's routes in one job should pass one Map.
   */
  fileCache?: Map<string, Promise<string>>;
}

export interface SourceResolution {
  ok: true;
  /** The repository path to edit. */
  path: string;
  editor: SourceEditor;
  confidence: 'exact' | 'pattern' | 'glob';
  /**
   * Every route the edit reaches. A content edit reaches its own route; a layout edit (see
   * `resolveLayout`) lists every route the template renders.
   */
  affectedRoutes: string[];
  /** markdown_frontmatter only: which keys carry each field. */
  fields: FieldMap;
  /** markdown_frontmatter only: how written values are quoted (`strip_quotes` for the pilot). */
  dialect: FrontmatterDialect;
  /** The rule that supplied the source, as written. */
  rule: SourceRule;
  layout: boolean;
}

export type SourceResolutionResult = SourceResolution | Refusal;

/** Fill a source template from a route match: `:slug` and `*` are substituted. */
function fillTemplate(template: string, values: Record<string, string>): string {
  return template.replace(/:[A-Za-z0-9_]+|\*/g, (token) => {
    // A `*` with no splat in the route is the source's own file glob, not a substitution.
    if (token === '*') return values['*'] ?? '*';
    return values[token.slice(1)] ?? token;
  });
}

function fieldMap(rule: SourceRule): FieldMap {
  if (!rule.fields) return DEFAULT_FIELDS;
  const fields: FieldMap = { ...DEFAULT_FIELDS };
  for (const [field, keys] of Object.entries(rule.fields)) {
    if (field === 'title' || field === 'description') fields[field] = keys;
  }
  return fields;
}

function capabilityRefusal(rule: SourceRule, changeType: ChangeTypeName, path: string): Refusal {
  const draft = path.includes('*') ? `a Markdown draft matching ${path}` : `the Markdown draft ${path}`;
  if (rule.editor === 'markdown_frontmatter' && changeType === 'schema.jsonld') {
    return refuse(
      'unsupported',
      `The source for this route is ${draft}, whose frontmatter has no JSON-LD field. Add the structured data in the site's build template, or use a page with HTML source.`,
      { path, editor: rule.editor },
    );
  }
  return refuse(
    'unsupported',
    `The ${rule.editor} source ${path} has no field for a ${changeType} change. Use a page with HTML source, or change the site's build template.`,
    { path, editor: rule.editor },
  );
}

function cannotExpress(rule: SourceRule, changeType: ChangeTypeName): boolean {
  return !EDITOR_CAPABILITIES[rule.editor].includes(changeType);
}

/** The successful resolution of one rule, with the rule's field map and quoting dialect. */
function resolution(
  rule: SourceRule,
  path: string,
  confidence: SourceResolution['confidence'],
  affectedRoutes: string[],
): SourceResolution {
  return {
    ok: true,
    path,
    editor: rule.editor,
    confidence,
    affectedRoutes,
    fields: fieldMap(rule),
    dialect: rule.frontmatterDialect,
    rule,
    layout: false,
  };
}

/**
 * The single gate every editable path goes through: the refusal for a path the site build writes,
 * or null when the path is a real source. Every resolver returns through it, because a path is no
 * safer for arriving from a glob, a frontmatter slug, a layout rule or the redirects config.
 */
function assertEditable(mapping: SiteMapping, path: string): Refusal | null {
  const entry = generatedEntries(mapping).find((candidate) => pathMatchesGlob(candidate.path, path));
  return entry ? refuse('unsupported', entry.reason, { path, generated: true }) : null;
}

/** Read a file through the caller's cache, so a page's routes share one pass over the drafts. */
function readCached(deps: ResolveDeps, path: string, readFile: (path: string) => Promise<string>): Promise<string> {
  const cache = deps.fileCache;
  if (!cache) return readFile(path);
  const cached = cache.get(path);
  if (cached) return cached;
  const reading = readFile(path);
  cache.set(path, reading);
  void reading.catch(() => cache.delete(path));
  return reading;
}

/**
 * Resolve a route whose build names the file after the post's frontmatter (`slug`, else the
 * slugified `title`) rather than after the file name. The pilot's tools/build_blog.py does this, so
 * `/blog/<slug>/` is `content/drafts/<anything>.md` whose content says `<slug>`.
 */
async function resolveByFrontmatterSlug(
  mapping: SiteMapping,
  rule: SourceRule,
  values: Record<string, string>,
  routePath: string,
  deps: ResolveDeps,
): Promise<SourceResolutionResult> {
  const slug = values.slug ?? values['*'];
  if (!slug) {
    return refuse(
      'invalid',
      `The rule for ${routePath} resolves by frontmatter slug, so its route pattern needs :slug (or a splat) to name the post.`,
      { routes: rule.routes },
    );
  }
  const readFile = deps.readFile;
  if (!readFile) {
    return refuse(
      'unsupported',
      `The rule for ${routePath} resolves routes by frontmatter slug, which needs readFile() to read the drafts matching ${rule.source}.`,
      { source: rule.source },
    );
  }
  const prefix = globPrefix(rule.source);
  const files = await deps.listFiles(prefix);
  const candidates = files.filter((file) => pathMatchesGlob(rule.source, file)).sort();
  const texts = await Promise.all(candidates.map((file) => readCached(deps, file, readFile)));
  const matches = candidates.filter((_, index) => pilotSlug(texts[index] ?? '') === slug);

  if (matches.length === 0) {
    return refuse(
      'not_found',
      `No file matching ${rule.source} has the slug "${slug}" in its frontmatter (or a title that slugifies to it). Check the draft exists and its slug or title is what the route names.`,
      { pattern: rule.source, slug, candidates },
    );
  }
  if (matches.length > 1) {
    return refuse(
      'ambiguous',
      `More than one draft has the slug "${slug}": ${matches.join(', ')}. Give the posts distinct slugs before changing this route.`,
      { pattern: rule.source, slug, candidates: matches },
    );
  }
  const found = matches[0]!;
  const generated = assertEditable(mapping, found);
  if (generated) return generated;
  return resolution(rule, found, 'glob', [routePath]);
}

/**
 * Resolve one route to the file that really holds its content.
 *
 * Rules are tried in order. A rule with `layout: true` is a shared template, not a page source, so it
 * never wins this lookup; a template edit resolves separately through `resolveLayout`, which lists
 * every route the template renders.
 */
export async function resolveSource(mapping: SiteMapping, route: string, deps: ResolveDeps): Promise<SourceResolutionResult> {
  const path = pathOf(route);
  let matchedAnyRule = false;

  for (const rule of mapping.rules) {
    const values = matchRoute(rule.routes, path);
    if (!values) continue;
    matchedAnyRule = true;
    if (rule.layout) continue;

    const resolved = rule.resolveBy === 'frontmatter_slug' ? rule.source : fillTemplate(rule.source, values);

    if (rule.generated) {
      return refuse(
        'unsupported',
        rule.generatedReason ??
          `${resolved} is written by the site build, so editing it would be overwritten at the next build. Change its source instead.`,
        { path: resolved, generated: true },
      );
    }

    if (deps.changeType) {
      if (cannotExpress(rule, deps.changeType)) return capabilityRefusal(rule, deps.changeType, resolved);
    }

    if (rule.resolveBy === 'frontmatter_slug') return resolveByFrontmatterSlug(mapping, rule, values, path, deps);

    const confidence: SourceResolution['confidence'] = resolved.includes('*')
      ? 'glob'
      : routePattern(rule.routes).exact
        ? 'exact'
        : 'pattern';

    if (resolved.includes('*')) {
      const prefix = globPrefix(resolved);
      const files = await deps.listFiles(prefix);
      const candidates = files.filter((file) => pathMatchesGlob(resolved, file)).sort();
      if (candidates.length === 0) {
        return refuse(
          'not_found',
          `No source file matches ${resolved} under ${prefix || 'the repository'}. Check the draft exists and its date suffix is right.`,
          {
            pattern: resolved,
            prefix,
          },
        );
      }
      if (candidates.length > 1) {
        return refuse(
          'ambiguous',
          `More than one file matches ${resolved}: ${candidates.join(', ')}. Rename the draft so the route names exactly one file.`,
          {
            pattern: resolved,
            candidates,
          },
        );
      }
      const candidate = candidates[0]!;
      const generated = assertEditable(mapping, candidate);
      if (generated) return generated;
      return resolution(rule, candidate, 'glob', [path]);
    }

    const generated = assertEditable(mapping, resolved);
    if (generated) return generated;

    return resolution(rule, resolved, confidence, [path]);
  }

  return refuse(
    'not_found',
    matchedAnyRule
      ? `Only a shared layout matches ${path}; add a rule for the page's own source, or edit the layout deliberately with resolveLayout().`
      : `No source mapping rule matches ${path}. Add a rule to the site's mapping (routes -> source file) before changing this page.`,
    { route: path },
  );
}

/**
 * Resolve the shared template that renders a route. A layout change reaches every route its
 * pattern matches, which is what the reach estimate counts; without a route list the reach is the
 * one route asked about, and the result says so by listing only that route.
 */
export interface LayoutReachDeps {
  /** Known site routes, used to expand the template's reach. */
  routes?: readonly string[];
  changeType?: ChangeTypeName;
}

export function resolveLayout(mapping: SiteMapping, route: string, deps: LayoutReachDeps = {}): SourceResolution | Refusal {
  const path = pathOf(route);
  for (const rule of mapping.rules) {
    const values = matchRoute(rule.routes, path);
    if (!values || !rule.layout) continue;
    const resolved = fillTemplate(rule.source, values);
    if (deps.changeType && !EDITOR_CAPABILITIES[rule.editor].includes(deps.changeType))
      return capabilityRefusal(rule, deps.changeType, resolved);
    const generated = assertEditable(mapping, resolved);
    if (generated) return generated;
    const reach = (deps.routes ?? [path]).filter((candidate) => routeMatches(rule.routes, candidate)).map(pathOf);
    return {
      ok: true,
      path: resolved,
      editor: rule.editor,
      confidence: resolved.includes('*') ? 'glob' : routePattern(rule.routes).exact ? 'exact' : 'pattern',
      affectedRoutes: [...new Set(reach.length ? reach : [path])],
      fields: fieldMap(rule),
      dialect: rule.frontmatterDialect,
      rule,
      layout: true,
    };
  }
  return refuse('not_found', `${path} has no shared-layout rule in the site's mapping.`, { route: path });
}

/** The redirects file a redirect change edits, or a refusal when the mapping has none. */
export function resolveRedirects(mapping: SiteMapping): { ok: true; path: string; format: 'netlify' } | Refusal {
  if (!mapping.redirects) {
    return refuse(
      'unsupported',
      'This site has no redirects file in its mapping, so a redirect change cannot be applied. Add the file to the mapping first.',
    );
  }
  const generated = assertEditable(mapping, mapping.redirects.file);
  if (generated) return generated;
  return { ok: true, path: mapping.redirects.file, format: mapping.redirects.format };
}
