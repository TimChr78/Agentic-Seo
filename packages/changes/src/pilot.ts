// How the pilot (TimChr78/martechsignal) names a blog post, ported from its build so the mapping
// resolves the same route the build writes.
//
// tools/build_blog.py, at commit b1b0bd3295f693944b8d7f783f2ab1712dd3eda0:
//   slug = meta.get('slug') or slugify(title)          (main, and build_post)
//   def slugify(title):
//       s = title.lower()
//       s = re.sub(r'[^a-z0-9\s-]', '', s)
//       s = re.sub(r'\s+', '-', s)
//       return s.strip('-')
// and parse_frontmatter reads a flat `key: value` line as `val.strip().strip('"').strip("'")`
// with `re.match(r'(\w+):\s*(.+)', line)`: anchored at the start of the line, so an indented line
// or a comment (`# slug: old`) is not a key. Both are ported faithfully, because a reader that
// matched mid-line would resolve a route the build never writes.
//
// The port has to use *Python's* character classes, not JavaScript's. Python's `str.isspace()`,
// `\s`, `str.strip()` and `str.split()` share one whitespace set that includes U+0085, U+001C–U+001F
// and the Unicode spaces (U+00A0, U+2000–U+200A, U+2028, U+2029, U+202F, U+205F, U+3000) but not
// U+FEFF, which JavaScript's `\s` and `trim()` do include. Python's `\w` is Unicode letters, digits
// and `_`. And Python's `.` stops only at `\n`, where JavaScript's also stops at `\r`, U+2028 and
// U+2029 — the difference that truncated a value at a line separator. The sets below are the
// output of `python3 -c '...isspace()...'`, and `test/fixtures/pilot/python-expectations.json`
// holds expectations generated by running the pilot's own functions.
//
// The draft's file name is not the route: `content/drafts/<title-slug>-<YYYY-MM-DD>.md` is a
// convention, and real drafts either carry a `slug` unrelated to the file name or carry none at
// all. A mapping that guessed from the file name would point a change at the wrong post, so it
// reads the drafts and compares their slugs instead.

export interface PilotFrontmatter {
  /** Flat keys, as the pilot's parser reads them (a `[a, b]` value becomes a list). */
  meta: Record<string, string | string[]>;
  body: string;
}

/**
 * Python's whitespace set as a character-class body: every character `str.isspace()` accepts, which
 * is exactly what `\s`, `str.strip()`, `str.split()` and `re`'s `\s` use for `str` patterns.
 */
const PYTHON_SPACE_CLASS = '\\t\\n\\v\\f\\r\\x1c-\\x1f \\x85\\xa0\\u1680\\u2000-\\u200a\\u2028\\u2029\\u202f\\u205f\\u3000';

const PYTHON_SPACE = new RegExp(`[${PYTHON_SPACE_CLASS}]`, 'u');
const PYTHON_SPACE_RUN = new RegExp(`[${PYTHON_SPACE_CLASS}]+`, 'gu');

/** Python's `str.strip()` with no argument: strips Python's whitespace, not JavaScript's. */
export function pythonStrip(text: string): string {
  let start = 0;
  let end = text.length;
  while (start < end && PYTHON_SPACE.test(text[start]!)) start += 1;
  while (end > start && PYTHON_SPACE.test(text[end - 1]!)) end -= 1;
  return text.slice(start, end);
}

/** Whether Python treats a character as whitespace (`chr(c).isspace()`). */
export function pythonIsSpace(char: string): boolean {
  return PYTHON_SPACE.test(char);
}

/** `str.strip('"')`: remove every leading and trailing `"`. */
function stripDoubleQuotes(value: string): string {
  return value.replace(/^"+/, '').replace(/"+$/, '');
}

/** `str.strip("'")`: remove every leading and trailing `'`. */
function stripSingleQuotes(value: string): string {
  return value.replace(/^'+/, '').replace(/'+$/, '');
}

/** `val.strip().strip('"').strip("'"): the pilot's scalar, in its order. */
function pilotScalar(value: string): string {
  return stripSingleQuotes(stripDoubleQuotes(pythonStrip(value)));
}

/** The pilot's slugify: lowercase, drop everything but `[a-z0-9 -]`, spaces to `-`, trim `-`. */
export function pilotSlugify(title: string): string {
  return title
    .toLowerCase()
    .replace(new RegExp(`[^a-z0-9${PYTHON_SPACE_CLASS}-]`, 'gu'), '')
    .replace(PYTHON_SPACE_RUN, '-')
    .replace(/^-+|-+$/g, '');
}

/**
 * Parse the frontmatter the way the pilot's `parse_frontmatter` does. The function splits the
 * block on `'\n'` (not on every line boundary), `strip()`s with Python's whitespace, and matches
 * `re.match(r'(\w+):\s*(.+)')` from the start of each line — so a key must start the line, a value
 * must have at least one character after the spaces, and the value runs to the end of the line
 * whatever else it contains (Python's `.` stops only at `\n`).
 */
export function parsePilotFrontmatter(text: string): PilotFrontmatter {
  if (!text.startsWith('---')) return { meta: {}, body: text };
  const open = text.indexOf('---');
  const close = text.indexOf('---', open + 3);
  if (close === -1) return { meta: {}, body: text };
  const raw = pythonStrip(text.slice(open + 3, close));
  const body = pythonStrip(text.slice(close + 3));
  const meta: Record<string, string | string[]> = {};
  for (const line of raw.split('\n')) {
    // `re.match(r'(\w+):\s*(.+)')`, anchored at the start: Python's `\w` is Unicode letters,
    // digits and `_`; `\s*` skips Python's whitespace; `(.+)` needs one more character.
    const matched = /^([\p{L}\p{N}_]+):/u.exec(line);
    if (!matched) continue;
    const rest = skipPythonSpace(line.slice(matched[0].length));
    if (rest === '') continue;
    const key = matched[1]!;
    const value = pilotScalar(rest);
    if (value.startsWith('[') && value.endsWith(']')) {
      meta[key] = value.slice(1, -1).split(',').map(pilotScalar);
    } else {
      meta[key] = value;
    }
  }
  return { meta, body };
}

/** The remainder of a line with Python's leading whitespace removed. */
function skipPythonSpace(text: string): string {
  let index = 0;
  while (index < text.length && PYTHON_SPACE.test(text[index]!)) index += 1;
  return text.slice(index);
}

/** The `slug` the pilot's build gives a draft, or null when it has neither a slug nor a title. */
export function pilotSlug(text: string): string | null {
  const { meta } = parsePilotFrontmatter(text);
  const declared = meta.slug;
  if (typeof declared === 'string' && declared !== '') return declared;
  const title = meta.title;
  if (typeof title !== 'string' || title === '') return null;
  return pilotSlugify(title);
}
